'use strict';
// Adversarial fixtures validate a trust boundary, not application/native acceptance.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { create, verify, hash } = require('../../tooling/resource-integrity.cjs');
fs.mkdirSync(path.join(__dirname, '.runs'), { recursive: true });
const run = fs.mkdtempSync(path.join(__dirname, '.runs/integrity-'));
const root = path.join(run, 'Tài nguyên spaces');
fs.mkdirSync(path.join(root, 'app'), { recursive: true });
const file = path.join(root, 'app/test.txt');
fs.writeFileSync(file, 'verified resource\n');
const spec = () => create(root, 'win32-x64', 'test-only', ['app']);
const bytes = Buffer.from(JSON.stringify(spec()));
let checks = 0;
const bad = f => { assert.throws(f); checks++; };
verify(root, bytes, hash(bytes), 'win32-x64', 'test-only'); checks++;
bad(() => verify(root, bytes, '0'.repeat(64), 'win32-x64', 'test-only'));
bad(() => verify(root, bytes, hash(bytes), 'darwin-x64', 'test-only'));
bad(() => verify(root, bytes, hash(bytes), 'win32-x64', 'wrong-version'));
fs.writeFileSync(file, 'tampered bytes'); bad(() => verify(root, bytes, hash(bytes), 'win32-x64', 'test-only'));
fs.writeFileSync(file, 'verified resource\n');
fs.writeFileSync(path.join(root, 'extra.txt'), 'extra'); bad(spec);
fs.unlinkSync(path.join(root, 'extra.txt'));
fs.writeFileSync(path.join(root, 'app/.env'), 'SECRET=fixture'); bad(spec);
fs.unlinkSync(path.join(root, 'app/.env'));
fs.unlinkSync(file); bad(() => verify(root, bytes, hash(bytes), 'win32-x64', 'test-only'));
bad(() => create(root, 'win32-x64', 'test-only', ['../escape']));
fs.mkdirSync(path.join(root, 'app/empty')); bad(() => verify(root, bytes, hash(bytes), 'win32-x64', 'test-only'));
const outside = path.join(run, 'outside'); fs.mkdirSync(outside);
const link = path.join(root, 'app/escape');
fs.symlinkSync(outside, link, process.platform === 'win32' ? 'junction' : 'dir');
bad(spec); fs.unlinkSync(link);
const result = { passed: checks, scope: 'Offline inventory/trusted hash, corruption, extra/missing files, target/version, forbidden credential path, traversal and directory-set checks; no native/installer certification' };
fs.writeFileSync(path.join(__dirname, 'integrity-checks.json'), JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify(result));
